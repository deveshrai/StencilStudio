# ---------------------------------------------------------------- fur strands
def sample_ellipse_edge(cx, cy, rx, ry, a0, a1, n):
    for i in range(n):
        a = a0 + (a1 - a0) * (i + random.random()) / n
        yield cx + rx * math.cos(a), cy + ry * math.sin(a), a


def strands():
    out = []
    # head outline: short, soft fur pointing outwards (a little longer on the cheeks)
    for x, y, a in sample_ellipse_edge(512, 500, 206, 234, math.pi * 0.55, math.pi * 1.45, 420):
        L = random.uniform(5, 13) * (1.35 if abs(math.sin(a)) < 0.45 else 1.0)
        dx, dy = math.cos(a), math.sin(a) * 0.8 + 0.25  # fur falls slightly downward
        n = math.hypot(dx, dy)
        dx, dy = dx / n, dy / n
        ex, ey = x + L * dx, y + L * dy
        col = random.choice(["#b97a40", "#c68a4c", "#a86c34", "#d39a5c"])
        out.append(f'<path d="M{x:.1f} {y:.1f} Q {(x+ex)/2+random.uniform(-2,2):.1f} {(y+ey)/2+random.uniform(-2,2):.1f} {ex:.1f} {ey:.1f}" stroke="{col}" stroke-opacity="0.75"/>')
    # ears: long, soft, flowing down
    for _ in range(260):
        x = random.uniform(220, 342)
        y = random.uniform(350, 650)
        L = random.uniform(12, 26)
        col = random.choice(["#7a4520", "#6a3a1a", "#8c522a", "#5a3014"])
        out.append(f'<path d="M{x:.1f} {y:.1f} q {random.uniform(-4,4):.1f} {L/2:.1f} {random.uniform(-5,5):.1f} {L:.1f}" stroke="{col}" stroke-opacity="0.5"/>')
    # face texture: fine strokes radiating from the nose
    for _ in range(520):
        x = random.uniform(318, 512)
        y = random.uniform(290, 700)
        L = random.uniform(5, 10)
        ang = math.atan2(y - 600, x - 512) + random.uniform(-0.25, 0.25)
        col = random.choice(["#c4864a", "#b27440", "#dca266"])
        out.append(f'<path d="M{x:.1f} {y:.1f} l {L*math.cos(ang):.1f} {L*math.sin(ang):.1f}" stroke="{col}" stroke-opacity="0.28"/>')
    return "\n".join(out)


